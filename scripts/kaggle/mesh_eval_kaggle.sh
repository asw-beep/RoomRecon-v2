#!/bin/bash
# Evaluate a mesh against a MuSHRoom laser scan with DN-Splatter's own protocol
# (eval_mesh_mushroom_vis_cull.py, unmodified) on a Kaggle T4, from the GPU machine.
# For when the GPU machine has no usable GPU: the protocol's visibility culling renders depth
# maps with pyrender (EGL) and needs a working graphics driver.
#   bash scripts/kaggle/mesh_eval_kaggle.sh push   <name> <room_dir> <mesh.ply>
#   bash scripts/kaggle/mesh_eval_kaggle.sh status <name>
#   bash scripts/kaggle/mesh_eval_kaggle.sh fetch  <name>   -> ~/roomrecon/kaggle-out/<name>/
# <room_dir> = .../room_datasets/<room> (gt_mesh.ply, icp_iphone.json, iphone/long_capture/).
# The mesh must be in the iPhone capture's frame, like DN-Splatter's own meshes.
# Libraries are pinned to the GPU machine's DN-Splatter env (open3d 0.18.0, trimesh 4.3.1,
# pyrender 0.1.45, PyOpenGL 3.1.0, numpy 1.26.4, scipy 1.13.0, tyro 0.8.3) in a venv on top of
# Kaggle's torch. If EGL does not work on Kaggle, it renders with OSMesa (software) instead and
# says so in out/env.txt. Needs: Kaggle CLI signed in, KAGGLE_USERNAME.
set -euo pipefail
KG="$HOME/.pixi/bin/kaggle"
DNS="$HOME/roomrecon/tools/dn-splatter"
CMD="$1"; NAME="$2"
U="${KAGGLE_USERNAME:?set KAGGLE_USERNAME to your Kaggle user name}"
SLUG="roomrecon-meval-${NAME//_/-}"   # data dataset (Kaggle slugs allow only letters, digits, "-")
KSLUG="$SLUG-run"                     # notebook

meta() {  # meta <dir> <slug>: dataset-metadata.json for a private dataset
  printf '{"title": "%s", "id": "%s/%s", "licenses": [{"name": "other"}]}\n' "$2" "$U" "$2" > "$1/dataset-metadata.json"
}
upload() {  # upload <dir> <slug>: create the dataset, or add a new version, then wait until ready
  local out
  if "$KG" datasets status "$U/$2" >/dev/null 2>&1; then
    out=$("$KG" datasets version -p "$1" -m "$(date -u +%FT%TZ)" -r zip -t -q 2>&1)
  else
    out=$("$KG" datasets create -p "$1" -r zip -t -q 2>&1)
  fi
  echo "$out"
  # the CLI can print an error and still exit 0
  if grep -qi "error" <<<"$out"; then echo "upload of $2 failed" >&2; return 1; fi
  for _ in $(seq 90); do
    [ "$("$KG" datasets status "$U/$2" 2>/dev/null)" = ready ] && return 0; sleep 10
  done
  echo "dataset $2 not ready after 15 min" >&2; return 1
}

case "$CMD" in
push)
  ROOMDIR="$3"; MESH="$4"
  ST="$(mktemp -d)"; G="$ST/data/gt"; mkdir -p "$G/iphone/long_capture" "$ST/data/pred" "$ST/kernel"
  cp "$ROOMDIR/gt_mesh.ply" "$ROOMDIR/icp_iphone.json" "$G/"
  LC="$ROOMDIR/iphone/long_capture"
  cp -r "$LC/depth" "$LC/transformations_colmap.json" "$LC/test.txt" "$G/iphone/long_capture/"
  cp "$MESH" "$ST/data/pred/mesh.ply"
  cp "$DNS/dn_splatter/eval/eval_mesh_mushroom_vis_cull.py" "$ST/data/"
  git -C "$DNS" rev-parse --short HEAD > "$ST/data/DN_SPLATTER_COMMIT"
  git -C "$DNS" diff --quiet HEAD -- dn_splatter/eval/eval_mesh_mushroom_vis_cull.py \
    || { echo "the eval script differs from DN-Splatter's commit; refusing" >&2; exit 1; }
  md5sum "$ST/data/pred/mesh.ply" > "$ST/data/pred/mesh.md5"
  meta "$ST/data" "$SLUG"; upload "$ST/data" "$SLUG"
  python3 - "$ST/kernel" "$U" "$SLUG" "$KSLUG" <<'EOF'
import json, sys
d, user, slug, kslug = sys.argv[1:]
src = r"""%%bash
# Generated by scripts/kaggle/mesh_eval_kaggle.sh - do not edit.
set -euo pipefail
IN=$(dirname "$(find /kaggle/input -name eval_mesh_mushroom_vis_cull.py | head -1)")
GT=$(dirname "$(find "$IN" -name gt_mesh.ply | head -1)")
OUT=/kaggle/working/out; mkdir -p "$OUT"
cp "$IN/DN_SPLATTER_COMMIT" "$IN/pred/mesh.md5" "$OUT/" 2>/dev/null || true
python3 -m venv --system-site-packages /tmp/ev
P=/tmp/ev/bin/python
$P -m pip install -q numpy==1.26.4 scipy==1.13.0 trimesh==4.3.1 pyrender==0.1.45 PyOpenGL==3.1.0 tyro==0.8.3 \
  opencv-python-headless==4.8.0.76 2>&1 | tail -3
# open3d 0.18.0 as on the GPU machine; 0.19.0 only if this Python has no 0.18 wheel (env.txt records it)
$P -m pip install -q open3d==0.18.0 2>&1 | tail -3 || $P -m pip install -q open3d==0.19.0 2>&1 | tail -3
probe() {  # probe <platform>: can pyrender render a depth map offscreen?
  PYOPENGL_PLATFORM=$1 timeout 120 $P -c "
import numpy as np, trimesh, pyrender
s = pyrender.Scene()
s.add(pyrender.Mesh.from_trimesh(trimesh.creation.box()))
pose = np.eye(4)
pose[2, 3] = 3.0
s.add_node(pyrender.Node(camera=pyrender.IntrinsicsCamera(100, 100, 50, 50), matrix=pose))
r = pyrender.OffscreenRenderer(100, 100)
d = r.render(s, pyrender.RenderFlags.DEPTH_ONLY)
assert d.max() > 0, 'empty depth'
print('render ok, max depth', float(d.max()))
"
}
cp "$IN/eval_mesh_mushroom_vis_cull.py" /tmp/eval.py
if probe egl; then RENDERER=egl
else
  apt-get -qq update >/dev/null && apt-get -qq install -y libosmesa6 >/dev/null
  probe osmesa
  RENDERER=osmesa
  sed -i 's/os.environ\["PYOPENGL_PLATFORM"\] = "egl"/os.environ["PYOPENGL_PLATFORM"] = "osmesa"/' /tmp/eval.py
fi
{ echo "renderer=$RENDERER"; $P -c "import sys, numpy, scipy, open3d, trimesh, pyrender, OpenGL, torch, tyro; print('python', sys.version.split()[0]); [print(m.__name__, m.__version__) for m in (numpy, scipy, open3d, trimesh, pyrender, OpenGL, torch, tyro)]"; nvidia-smi -L || true; } > "$OUT/env.txt" 2>&1
cat "$OUT/env.txt"
cd /tmp
set +e
PYOPENGL_PLATFORM=$RENDERER $P /tmp/eval.py --gt-mesh-path "$GT" --pred-mesh-path "$IN/pred/mesh.ply" \
  --device iphone --output "$OUT" --output-same-as-pred-mesh False > "$OUT/eval.log" 2>&1
echo "EVAL_EXIT=$?" | tee -a "$OUT/eval.log"
tail -25 "$OUT/eval.log"
ls -la "$OUT"
"""
nb = {"cells": [{"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
                 "source": src.splitlines(keepends=True)}],
      "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}},
      "nbformat": 4, "nbformat_minor": 5}
json.dump(nb, open(f"{d}/{kslug}.ipynb", "w"), indent=1)
json.dump({"id": f"{user}/{kslug}", "title": kslug, "code_file": f"{kslug}.ipynb", "language": "python",
           "kernel_type": "notebook", "is_private": True, "enable_gpu": True, "enable_internet": True,
           "enable_tpu": False, "machine_shape": "NvidiaTeslaT4",
           "dataset_sources": [f"{user}/{slug}"],
           "competition_sources": [], "kernel_sources": []}, open(f"{d}/kernel-metadata.json", "w"), indent=2)
EOF
  "$KG" kernels push -p "$ST/kernel" --accelerator NvidiaTeslaT4
  rm -rf "$ST"
  echo "pushed $U/$KSLUG. Watch: bash $0 status $NAME"
  ;;
status) "$KG" kernels status "$U/$KSLUG" ;;
fetch)
  DST="$HOME/roomrecon/kaggle-out/$NAME"; mkdir -p "$DST"
  "$KG" kernels output "$U/$KSLUG" -p "$DST" --force
  ls -la "$DST" "$DST"/out 2>/dev/null | head -20
  ;;
*) echo "usage: $0 push|status|fetch <name> ..." >&2; exit 2 ;;
esac
