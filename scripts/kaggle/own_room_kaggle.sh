#!/bin/bash
# Train an own room on a Kaggle T4 from the GPU machine (fallback when the shared A100 is full).
# Uploads the repo at HEAD and the processed capture as two private datasets, then pushes a
# one-cell notebook that runs scripts/kaggle/own_room_session.sh in a GPU session.
#   bash scripts/kaggle/own_room_kaggle.sh push   <room> <run_id> <processed_dir> <iters>
#   bash scripts/kaggle/own_room_kaggle.sh status <room>
#   bash scripts/kaggle/own_room_kaggle.sh fetch  <room> <run_id>   -> ~/roomrecon/scenes/<room>/<run_id>/kaggle/
# Needs: Kaggle CLI signed in (~/.kaggle/credentials.json from `kaggle auth login`, or access_token),
#        KAGGLE_USERNAME (the name in your kaggle.com profile URL). SKIP_UPLOAD=1 reuses the datasets.
set -euo pipefail
KG="$HOME/.pixi/bin/kaggle"
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
CMD="$1"; ROOM="$2"
U="${KAGGLE_USERNAME:?set KAGGLE_USERNAME to your Kaggle user name}"
SLUG="roomrecon-own-$ROOM"           # data dataset
KSLUG="$SLUG-train"                  # notebook (its own slug: the dataset's slug gave 409 Conflict)
CODE_SLUG="roomrecon-code"

meta() {  # meta <dir> <slug>: dataset-metadata.json for a private dataset
  printf '{"title": "%s", "id": "%s/%s", "licenses": [{"name": "other"}]}\n' "$2" "$U" "$2" > "$1/dataset-metadata.json"
}
upload() {  # upload <dir> <slug>: create the dataset, or add a new version, then wait until ready
  if "$KG" datasets status "$U/$2" >/dev/null 2>&1; then
    "$KG" datasets version -p "$1" -m "$(date -u +%FT%TZ)" -r zip -q
  else
    "$KG" datasets create -p "$1" -r zip -q
  fi
  for _ in $(seq 60); do
    [ "$("$KG" datasets status "$U/$2" 2>/dev/null)" = ready ] && return 0; sleep 10
  done
  echo "dataset $2 not ready after 10 min" >&2; return 1
}

case "$CMD" in
push)
  RUN="$3"; DATA="$4"; ITERS="$5"
  ST="$(mktemp -d)"; mkdir -p "$ST/code/repo" "$ST/data/processed" "$ST/kernel"
  # code: the committed tree only (what ran is what is in git), plus its commit id
  git -C "$REPO" diff --quiet HEAD -- scripts roomrecon env || { echo "uncommitted changes in scripts/roomrecon/env: commit first" >&2; exit 1; }
  git -C "$REPO" archive HEAD | tar -x -C "$ST/code/repo"
  git -C "$REPO" rev-parse HEAD > "$ST/code/repo/COMMIT"
  meta "$ST/code" "$CODE_SLUG"; [ -n "${SKIP_UPLOAD:-}" ] || upload "$ST/code" "$CODE_SLUG"
  # data: full-resolution images, depth, poses and seed points (normals are made in the session)
  cp -r "$DATA/images" "$DATA/depth" "$DATA/transforms.json" "$DATA/iphone_pointcloud.ply" "$ST/data/processed/"
  meta "$ST/data" "$SLUG"; [ -n "${SKIP_UPLOAD:-}" ] || upload "$ST/data" "$SLUG"
  python3 - "$ST/kernel" "$U" "$SLUG" "$KSLUG" "$CODE_SLUG" "$ROOM" "$RUN" "$ITERS" "$(cat "$ST/code/repo/COMMIT")" <<'EOF'
import json, sys
d, user, slug, kslug, code, room, run, iters, commit = sys.argv[1:]
src = f"""%%bash
# Generated by scripts/kaggle/own_room_kaggle.sh - do not edit. RoomRecon @ {commit}
set -euo pipefail
S=$(find /kaggle/input -path '*scripts/kaggle/own_room_session.sh' | head -1)
rm -rf /tmp/repo && cp -r "$(dirname "$(dirname "$(dirname "$S")")")" /tmp/repo
bash /tmp/repo/scripts/kaggle/own_room_session.sh {room} {run} {iters}
"""
nb = {"cells": [{"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
                 "source": src.splitlines(keepends=True)}],
      "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}},
      "nbformat": 4, "nbformat_minor": 5}
json.dump(nb, open(f"{d}/{kslug}.ipynb", "w"), indent=1)
json.dump({"id": f"{user}/{kslug}", "title": kslug, "code_file": f"{kslug}.ipynb", "language": "python",
           "kernel_type": "notebook", "is_private": True, "enable_gpu": True, "enable_internet": True,
           "enable_tpu": False, "machine_shape": "NvidiaTeslaT4",
           "dataset_sources": [f"{user}/{code}", f"{user}/{slug}"],
           "competition_sources": [], "kernel_sources": []}, open(f"{d}/kernel-metadata.json", "w"), indent=2)
EOF
  "$KG" kernels push -p "$ST/kernel" --accelerator NvidiaTeslaT4
  rm -rf "$ST"
  echo "pushed $U/$KSLUG: run $RUN, $ITERS steps. Watch: bash $0 status $ROOM"
  ;;
status) "$KG" kernels status "$U/$KSLUG" ;;
fetch)
  RUN="$3"; DST="$HOME/roomrecon/scenes/$ROOM/$RUN/kaggle"; mkdir -p "$DST"
  "$KG" kernels output "$U/$KSLUG" -p "$DST" --force
  ls -la "$DST" "$DST"/out 2>/dev/null | head -40
  ;;
*) echo "usage: $0 push|status|fetch <room> ..." >&2; exit 2 ;;
esac
